from odoo import api, fields, models
from odoo.exceptions import AccessError, ValidationError
from odoo.tools import BinaryBytes, file_open

from .res_company import HEX_COLOR

PARAM_PREFIX = 'ydod_web_backend_theme.'
SCSS_PATH = '/ydod_web_backend_theme/static/src/scss/colors.scss'
SCSS_URL = '/_custom/web._assets_primary_variables' + SCSS_PATH
SCSS_BUNDLE = 'web._assets_primary_variables'

# settings field -> SCSS variable written in the generated asset
COLOR_VARIABLES = {
    'ydod_color_brand': '$o-brand-odoo',
    'ydod_color_primary': '$o-brand-primary',
    'ydod_color_success': '$o-success',
    'ydod_color_info': '$o-info',
    'ydod_color_warning': '$o-warning',
    'ydod_color_danger': '$o-danger',
    'ydod_appbar_bg': '$ydod-appbar-bg',
    'ydod_appbar_text': '$ydod-appbar-text',
    'ydod_appbar_active': '$ydod-appbar-active',
}


class ResConfigSettings(models.TransientModel):
    _inherit = 'res.config.settings'

    ydod_color_brand = fields.Char(string='Brand Colour', config_parameter=PARAM_PREFIX + 'color_brand')
    ydod_color_primary = fields.Char(string='Primary Colour', config_parameter=PARAM_PREFIX + 'color_primary')
    ydod_color_success = fields.Char(string='Success Colour', config_parameter=PARAM_PREFIX + 'color_success')
    ydod_color_info = fields.Char(string='Info Colour', config_parameter=PARAM_PREFIX + 'color_info')
    ydod_color_warning = fields.Char(string='Warning Colour', config_parameter=PARAM_PREFIX + 'color_warning')
    ydod_color_danger = fields.Char(string='Danger Colour', config_parameter=PARAM_PREFIX + 'color_danger')
    ydod_appbar_bg = fields.Char(string='App Bar Background', config_parameter=PARAM_PREFIX + 'appbar_bg')
    ydod_appbar_text = fields.Char(string='App Bar Text', config_parameter=PARAM_PREFIX + 'appbar_text')
    ydod_appbar_active = fields.Char(string='App Bar Active Item', config_parameter=PARAM_PREFIX + 'appbar_active')

    ydod_background_image = fields.Binary(related='company_id.ydod_background_image', readonly=False)
    ydod_background_color = fields.Char(related='company_id.ydod_background_color', readonly=False)
    ydod_favicon = fields.Binary(related='company_id.ydod_favicon', readonly=False)

    @api.constrains(*COLOR_VARIABLES)
    def _check_ydod_colors(self):
        for settings in self:
            for fname in COLOR_VARIABLES:
                color = settings[fname]
                if color and not HEX_COLOR.match(color):
                    raise ValidationError(self.env._(
                        '"%(color)s" is not a valid colour for %(field)s: use a hex value such as #714B67.',
                        color=color, field=settings._fields[fname].string))

    def _ydod_get_colors(self):
        params = self.env['ir.config_parameter'].sudo()
        return {
            fname: params.get_str(self._fields[fname].config_parameter) or False
            for fname in COLOR_VARIABLES
        }

    def set_values(self):
        self._check_ydod_colors()
        old_colors = self._ydod_get_colors()
        super().set_values()
        if self._ydod_get_colors() != old_colors:
            self._ydod_write_scss()

    def _ydod_write_scss(self):
        """Write the colour overrides into the generated SCSS attachment."""
        colors = self._ydod_get_colors()
        if not any(colors.values()):
            self._ydod_remove_assets()
            return
        lines = ['// Generated by yDoD Backend Theme from General Settings.']
        lines += [
            f'{COLOR_VARIABLES[fname]}: {color};'
            for fname, color in colors.items() if color
        ]
        with file_open(SCSS_PATH.lstrip('/'), 'r') as default_file:
            lines.append(default_file.read())
        raw = BinaryBytes('\n'.join(lines).encode(), filename='colors.scss')

        Attachment = self.env['ir.attachment'].sudo()
        attachment = Attachment.search([('url', '=', SCSS_URL)], limit=1)
        if attachment:
            attachment.write({'raw': raw})
        else:
            Attachment.create({
                'name': 'colors.scss',
                'type': 'binary',
                'mimetype': 'text/scss',
                'raw': raw,
                'url': SCSS_URL,
                'public': True,
            })

        Asset = self.env['ir.asset'].sudo()
        asset = Asset.search([('path', '=', SCSS_URL)], limit=1)
        values = {
            'name': 'yDoD Backend Theme Colours',
            'bundle': SCSS_BUNDLE,
            'directive': 'replace',
            'target': SCSS_PATH,
            'path': SCSS_URL,
            'active': True,
        }
        # writing the asset also invalidates the cached bundles
        if asset:
            asset.write(values)
        else:
            Asset.create(values)

    @api.model
    def _ydod_remove_assets(self):
        self.env['ir.asset'].sudo().search([('path', '=', SCSS_URL)]).unlink()
        self.env['ir.attachment'].sudo().search([('url', '=', SCSS_URL)]).unlink()

    @api.model
    def _ydod_remove_theme(self):
        self.env['ir.config_parameter'].sudo().search([('key', '=like', PARAM_PREFIX + '%')]).unlink()
        self._ydod_remove_assets()

    def action_ydod_reset_theme(self):
        if not self.env.user.has_group('base.group_system'):
            raise AccessError(self.env._('Only administrators can reset the backend theme.'))
        self._ydod_remove_theme()
        return {'type': 'ir.actions.client', 'tag': 'reload'}
